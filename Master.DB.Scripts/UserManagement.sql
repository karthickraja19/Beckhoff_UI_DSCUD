CREATE PROCEDURE [dbo].[sp_UpdateUser]
    @UserID INT,
    @Username NVARCHAR(100),
    @Password NVARCHAR(100),
    @ReEnterPassword NVARCHAR(100),
    @Department NVARCHAR(100)
AS
BEGIN
    SET NOCOUNT ON;

    -- Optional: check if username is used by another user
    IF EXISTS (SELECT 1 FROM Users WHERE Username = @Username AND UserID <> @UserID)
    BEGIN
        RAISERROR('Username already exists for another user.', 16, 1);
        RETURN;
    END

    UPDATE Users
    SET Username = @Username,
        Password = @Password,
        ReEnterPassword = @ReEnterPassword,
        Department = @Department
    WHERE UserID = @UserID;
END
