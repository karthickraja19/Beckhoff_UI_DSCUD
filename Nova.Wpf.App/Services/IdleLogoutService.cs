using System;
using System.Windows;
using System.Windows.Input;
using System.Windows.Threading;
using Nova.Abstractions.Data;
using Nova.Abstractions.Services;

namespace Nova.Wpf.App.Services
{
    /// <summary>
    /// Signs out an idle Level 2 or Level 3 operator - Audio SW DFM v5.4 slide 39:
    /// "For Level 2 and Level 3 users, if no operation is performed within 5 minutes,
    /// the system automatically logs out the user".
    /// </summary>
    /// <remarks>
    /// <para>
    /// Level 1 is deliberately exempt. The slide names only Levels 2 and 3, and those
    /// are the levels that can change something - a Level 1 operator watching a
    /// running machine should not be signed out from under a screen they are only
    /// reading.
    /// </para>
    /// <para>
    /// Activity is taken from <see cref="InputManager"/>, which sees every keyboard
    /// and mouse event in the application before it reaches a control. Watching a
    /// window's own events instead would miss input inside popups and dialogs, and an
    /// operator working a modal would be signed out mid-edit.
    /// </para>
    /// <para>
    /// The timer ticks once a second rather than being reset on every keystroke: a
    /// reset per input event on a touch screen is thousands of timer restarts a
    /// minute, and the requirement is a five-minute resolution.
    /// </para>
    /// </remarks>
    public sealed class IdleLogoutService : IDisposable
    {
        /// <summary>Slide 39's five minutes.</summary>
        private static readonly TimeSpan IdleLimit = TimeSpan.FromMinutes(5);

        private readonly IAppSession _session;
        private readonly IAccessLog _log;
        private readonly DispatcherTimer _timer;

        private DateTime _lastActivity = DateTime.Now;
        private bool _disposed;

        public IdleLogoutService(IAppSession session, IAccessLog log)
        {
            _session = session;
            _log = log;

            _timer = new DispatcherTimer(DispatcherPriority.Background)
            {
                Interval = TimeSpan.FromSeconds(1)
            };
            _timer.Tick += OnTick;
        }

        public void Start()
        {
            if (_disposed)
                return;

            InputManager.Current.PreProcessInput += OnPreProcessInput;
            _lastActivity = DateTime.Now;
            _timer.Start();
        }

        public void Stop()
        {
            _timer.Stop();
            if (InputManager.Current != null)
                InputManager.Current.PreProcessInput -= OnPreProcessInput;
        }

        private void OnPreProcessInput(object sender, PreProcessInputEventArgs e)
        {
            // Only real operator input counts. InputManager also raises synthetic
            // events - a mouse move generated by layout, keyboard focus churn - and
            // treating those as activity would keep a session alive on an untouched
            // machine, which is the one thing this service exists to prevent.
            InputEventArgs input = e.StagingItem == null ? null : e.StagingItem.Input;
            if (input is KeyEventArgs ||
                input is TextCompositionEventArgs ||
                input is MouseButtonEventArgs ||
                input is MouseWheelEventArgs ||
                input is TouchEventArgs ||
                input is StylusEventArgs)
            {
                _lastActivity = DateTime.Now;
            }
        }

        private void OnTick(object sender, EventArgs e)
        {
            if (!_session.IsLoggedIn)
            {
                // Nothing to time out. Keep the clock current so the countdown starts
                // from the next sign-in rather than from whenever input last happened.
                _lastActivity = DateTime.Now;
                return;
            }

            if (_session.Level < AccessLevel.Level2)
                return;

            if (DateTime.Now - _lastActivity < IdleLimit)
                return;

            string name = _session.UserName;
            int level = (int)_session.Level;

            _session.Logout();
            _lastActivity = DateTime.Now;

            if (_log != null)
                _log.Logout(name, level, "automatic - idle for " + (int)IdleLimit.TotalMinutes + " minutes");
        }

        public void Dispose()
        {
            if (_disposed)
                return;
            _disposed = true;

            Stop();
            _timer.Tick -= OnTick;
        }
    }
}
